GEM_COLOURS = {
    '#': (11, 14, 20, 255),
    'a': (210, 246, 252, 255), 'b': (142, 227, 242, 255), 'c': (90, 209, 232, 255),
    'd': (90, 209, 232, 255), 'e': (58, 160, 190, 255), 'f': (34, 104, 130, 255),
}


def gem():
    img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(GEM):
        for x, c in enumerate(row):
            if c in GEM_COLOURS:
                img.putpixel((x, y), GEM_COLOURS[c])
    img.save(HERE / 'gem.png')


def font():
    cell_w, cell_h = (5 + 2 * PAD) * SCALE, (7 + 2 * PAD) * SCALE
    per_row = 16
    rows = -(-len(GLYPHS) // per_row)
    page = Image.new('RGBA', (cell_w * per_row, cell_h * rows), (0, 0, 0, 0))
    lines = [
        'info face="pixel" size=%d bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0' % (7 * SCALE),
        'common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0' % (9 * SCALE, 7 * SCALE, page.width, page.height),
        'page id=0 file="pixel.png"',
        'chars count=%d' % len(GLYPHS),
    ]
    for i, (ch, rows_) in enumerate(GLYPHS.items()):
        ox, oy = (i % per_row) * cell_w + PAD * SCALE, (i // per_row) * cell_h + PAD * SCALE
        for y, row in enumerate(rows_):
            for x, c in enumerate(row):
                if c == '#':
                    for dy in range(SCALE):
                        for dx in range(SCALE):
                            page.putpixel((ox + x * SCALE + dx, oy + y * SCALE + dy), (255, 255, 255, 255))
        lines.append('char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15' % (
            ord(ch), ox, oy, 5 * SCALE, 7 * SCALE, (5 + GAP) * SCALE))
    page.save(HERE / 'pixel.png')
    (HERE / 'pixel.fnt').write_text('\n'.join(lines) + '\n')


gem()
font()
