# Draws the gym's own HUD art, which the game reads and never this script:
#   gem.png    a 16x16 gem, the picture the `badge` panel shows (`"for": "ui"`)
#   pixel.png  the page of `pixel.fnt`, an AngelCode BMFont (text) of a 5x7 pixel face drawn at
#   pixel.fnt  `SCALE` canvas pixels a dot: A-Z, 0-9 and the punctuation in GLYPHS
# Run from the repo's root: python3 games/demo_gameui/assets/art.py
